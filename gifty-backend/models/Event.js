const mongoose = require('mongoose');

const eventSchema = new mongoose.Schema({
    user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'User',
        required: true,
        immutable: true
    },
    recipient: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Recipient',
        required: true
    },
    name: {
        type: String,
        required: true
    },
    date: {
        type: Date,
        required: true
    },
    type: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'EventType',
        required: true
    },
    // Occurrences of a recurring event point at it (services/recurringEventService)
    series: {
        type: mongoose.Schema.Types.ObjectId,
        ref: 'Event',
        index: true
    },
    // The recipient's upcoming birthday, kept in step by birthdayEventService
    // A recurring event whose pre-series occurrences have been adopted
    seriesLinked: {
        type: Boolean
    },
    isAutoBirthday: {
        type: Boolean
    },
    isSystemGenerated: {
        type: Boolean,
        default: false,
        description: 'Indicates if this event was auto-generated by the system'
    },
    // A generated holiday whose next occurrence the yearly job already made
    rolledForward: {
        type: Boolean
    },
    recurring: {
        frequency: {
            type: String,
            enum: ['None', 'Daily', 'Weekly', 'Monthly', 'Yearly'],
            default: 'None'
        },
        until: {
            type: Date,
            required: function() { return this.recurring.frequency !== 'None'; }
        },
        exceptions: [{ 
            type: Date,
            required: false
        }]
    },
    reminder: {
        isSet: {
            type: Boolean,
            default: false
        },
        time: {
            type: Date
        },
        method: {
            type: String,
            enum: ['Email', 'Push Notification', 'SMS'],
            default: 'Email'
        }
    }
}, {
    timestamps: true
});

const Event = mongoose.model('Event', eventSchema);
module.exports = Event;